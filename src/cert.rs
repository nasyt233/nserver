//! TLS certificate discovery and expiry inspection via the openssl CLI.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use chrono::{DateTime, NaiveDateTime, TimeZone, Utc};

use crate::config::NginxConfig;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CertStatus {
    Ok,
    Warning,
    Critical,
    Expired,
    Unknown,
}

impl CertStatus {
    pub fn label(self) -> &'static str {
        match self {
            Self::Ok => "正常",
            Self::Warning => "即将到期",
            Self::Critical => "紧急",
            Self::Expired => "已过期",
            Self::Unknown => "未知",
        }
    }
}

#[derive(Debug, Clone)]
pub struct CertInfo {
    pub path: PathBuf,
    pub domains: Vec<String>,
    pub subject: Option<String>,
    pub issuer: Option<String>,
    pub not_after: Option<DateTime<Utc>>,
    pub days_left: Option<i64>,
    pub sans: Vec<String>,
    pub error: Option<String>,
}

impl CertInfo {
    pub fn status(&self) -> CertStatus {
        match self.days_left {
            Some(days) if days < 0 => CertStatus::Expired,
            Some(days) if days <= 7 => CertStatus::Critical,
            Some(days) if days <= 30 => CertStatus::Warning,
            Some(_) => CertStatus::Ok,
            None => CertStatus::Unknown,
        }
    }

    pub fn days_label(&self) -> String {
        match self.days_left {
            Some(days) if days < 0 => format!("已过期 {} 天", -days),
            Some(0) => "今天到期".to_string(),
            Some(days) => format!("{days} 天"),
            None => "—".to_string(),
        }
    }

    pub fn expires_label(&self) -> String {
        self.not_after
            .map(|dt| dt.format("%Y-%m-%d").to_string())
            .unwrap_or_else(|| "—".to_string())
    }

    pub fn display_name(&self) -> String {
        if !self.domains.is_empty() {
            self.domains.join(", ")
        } else if !self.sans.is_empty() {
            self.sans.join(", ")
        } else {
            self.subject
                .clone()
                .unwrap_or_else(|| self.path.display().to_string())
        }
    }

    pub fn primary_domain(&self) -> String {
        self.domains
            .first()
            .cloned()
            .or_else(|| self.sans.first().cloned())
            .or_else(|| self.subject.clone())
            .unwrap_or_else(|| self.path.display().to_string())
    }
}

pub fn discover(config: &NginxConfig) -> Vec<CertInfo> {
    let openssl = find_openssl();
    let mut grouped: BTreeMap<PathBuf, Vec<String>> = BTreeMap::new();
    for server in &config.servers {
        if let Some(path) = &server.cert_path {
            let entry = grouped.entry(path.clone()).or_default();
            if !server.names.is_empty() {
                for name in &server.names {
                    if !entry.contains(name) {
                        entry.push(name.clone());
                    }
                }
            }
        }
    }

    let mut certs = Vec::new();
    let referenced: Vec<PathBuf> = grouped.keys().cloned().collect();
    for (path, domains) in grouped {
        let mut info = CertInfo {
            path: path.clone(),
            domains,
            subject: None,
            issuer: None,
            not_after: None,
            days_left: None,
            sans: Vec::new(),
            error: None,
        };
        match &openssl {
            None => info.error = Some("未找到 openssl，无法读取证书。".into()),
            Some(bin) => match inspect_cert(bin, &path) {
                Ok(details) => {
                    info.subject = details.subject;
                    info.issuer = details.issuer;
                    info.not_after = details.not_after;
                    info.sans = details.sans;
                    info.days_left = details
                        .not_after
                        .map(|dt| (dt.date_naive() - Utc::now().date_naive()).num_days());
                }
                Err(err) => info.error = Some(err),
            },
        }
        if info.domains.is_empty() {
            info.domains = info.sans.clone();
        }
        certs.push(info);
    }

    // Also show certificates generated by nserver in <config>/ssl.
    let ssl_dir = config.config_dir.join("ssl");
    if let Ok(entries) = std::fs::read_dir(&ssl_dir) {
        let mut files: Vec<PathBuf> = entries
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| {
                path.extension()
                    .map(|ext| ext == "pem" || ext == "crt")
                    .unwrap_or(false)
            })
            .collect();
        files.sort();
        for path in files {
            if referenced.contains(&path) {
                continue;
            }
            let mut info = CertInfo {
                path: path.clone(),
                domains: Vec::new(),
                subject: None,
                issuer: None,
                not_after: None,
                days_left: None,
                sans: Vec::new(),
                error: None,
            };
            match &openssl {
                None => info.error = Some("未找到 openssl，无法读取证书。".into()),
                Some(bin) => match inspect_cert(bin, &path) {
                    Ok(details) => {
                        info.subject = details.subject;
                        info.issuer = details.issuer;
                        info.not_after = details.not_after;
                        info.sans = details.sans;
                        info.days_left = details
                            .not_after
                            .map(|dt| (dt.date_naive() - Utc::now().date_naive()).num_days());
                    }
                    Err(err) => info.error = Some(err),
                },
            }
            info.domains = info.sans.clone();
            certs.push(info);
        }
    }
    certs.sort_by(|a, b| {
        let ka = a.days_left.unwrap_or(i64::MAX);
        let kb = b.days_left.unwrap_or(i64::MAX);
        ka.cmp(&kb)
            .then_with(|| a.display_name().cmp(&b.display_name()))
    });
    certs
}

pub fn generate_self_signed(
    domain: &str,
    config_dir: &Path,
    days: u32,
) -> Result<(PathBuf, PathBuf), String> {
    let domain = domain.trim();
    if domain.is_empty()
        || domain.contains('/')
        || domain.contains(char::is_whitespace)
        || domain.contains("..")
    {
        return Err("域名格式无效。".into());
    }
    let Some(bin) = find_openssl() else {
        return Err("没有找到 openssl。".into());
    };
    let dir = config_dir.join("ssl");
    std::fs::create_dir_all(&dir).map_err(|e| format!("创建 ssl 目录失败：{e}"))?;
    let cert = dir.join(format!("{domain}.pem"));
    let key = dir.join(format!("{domain}.key"));
    if cert.exists() || key.exists() {
        return Err(format!("证书文件已存在：{}", cert.display()));
    }
    let output = Command::new(bin)
        .env("LC_ALL", "C")
        .args([
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-nodes",
            "-days",
            &days.to_string(),
            "-subj",
            &format!("/CN={domain}"),
            "-addext",
            &format!("subjectAltName=DNS:{domain}"),
            "-keyout",
        ])
        .arg(&key)
        .arg("-out")
        .arg(&cert)
        .output()
        .map_err(|e| format!("执行 openssl 失败：{e}"))?;
    if !output.status.success() {
        let _ = std::fs::remove_file(&cert);
        let _ = std::fs::remove_file(&key);
        return Err(String::from_utf8_lossy(&output.stderr).trim().to_string());
    }
    Ok((cert, key))
}

fn find_openssl() -> Option<PathBuf> {
    if let Some(path) = std::env::var_os("OPENSSL_BIN") {
        let path = PathBuf::from(path);
        if path.is_file() {
            return Some(path);
        }
    }
    for candidate in ["/usr/bin/openssl", "/usr/local/bin/openssl", "/bin/openssl"] {
        let path = PathBuf::from(candidate);
        if path.is_file() {
            return Some(path);
        }
    }
    std::env::var_os("PATH").and_then(|paths| {
        std::env::split_paths(&paths)
            .map(|dir| dir.join("openssl"))
            .find(|p| p.is_file())
    })
}

#[derive(Debug, Default)]
struct CertDetails {
    subject: Option<String>,
    issuer: Option<String>,
    not_after: Option<DateTime<Utc>>,
    sans: Vec<String>,
}

fn inspect_cert(bin: &Path, path: &Path) -> Result<CertDetails, String> {
    let output = Command::new(bin)
        .env("LC_ALL", "C")
        .arg("x509")
        .arg("-in")
        .arg(path)
        .arg("-noout")
        .arg("-subject")
        .arg("-issuer")
        .arg("-enddate")
        .arg("-ext")
        .arg("subjectAltName")
        .output()
        .map_err(|e| format!("无法执行 openssl：{e}"))?;
    if !output.status.success() {
        let err = String::from_utf8_lossy(&output.stderr);
        return Err(format!("读取证书失败：{}", err.trim()));
    }
    let text = String::from_utf8_lossy(&output.stdout);
    parse_openssl_output(&text).ok_or_else(|| "无法解析证书输出。".to_string())
}

fn parse_openssl_output(text: &str) -> Option<CertDetails> {
    let mut details = CertDetails::default();
    let mut in_san = false;
    for raw in text.lines() {
        let line = raw.trim();
        if let Some(value) = line.strip_prefix("subject=") {
            details.subject = Some(value.trim().to_string());
            in_san = false;
        } else if let Some(value) = line.strip_prefix("issuer=") {
            details.issuer = Some(value.trim().to_string());
            in_san = false;
        } else if let Some(value) = line.strip_prefix("notAfter=") {
            details.not_after = parse_openssl_date(value.trim());
            in_san = false;
        } else if line.starts_with("X509v3 Subject Alternative Name") {
            in_san = true;
        } else if in_san && !line.is_empty() {
            details.sans = line
                .split(',')
                .filter_map(|item| {
                    let item = item.trim();
                    item.strip_prefix("DNS:")
                        .or_else(|| item.strip_prefix("IP Address:"))
                        .map(|s| s.trim().to_string())
                })
                .collect();
            in_san = false;
        }
    }
    if details.subject.is_none() && details.not_after.is_none() {
        None
    } else {
        Some(details)
    }
}

pub fn parse_openssl_date(value: &str) -> Option<DateTime<Utc>> {
    let value = value.trim();
    let value = value.strip_suffix(" GMT").unwrap_or(value);
    if let Ok(naive) = NaiveDateTime::parse_from_str(value, "%b %e %H:%M:%S %Y") {
        return Some(Utc.from_utc_datetime(&naive));
    }
    let normalized = value.split_whitespace().collect::<Vec<_>>().join(" ");
    if let Ok(naive) = NaiveDateTime::parse_from_str(&normalized, "%b %d %H:%M:%S %Y") {
        return Some(Utc.from_utc_datetime(&naive));
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_openssl_date() {
        let date = parse_openssl_date("Jun  1 12:34:56 2027 GMT").unwrap();
        assert_eq!(
            date.format("%Y-%m-%d %H:%M:%S").to_string(),
            "2027-06-01 12:34:56"
        );
    }

    #[test]
    fn parses_certificate_output() {
        let text = "subject=CN = example.com\nissuer=C = US, O = Let's Encrypt\nnotAfter=Nov 21 12:00:00 2026 GMT\nX509v3 Subject Alternative Name:\n    DNS:example.com, DNS:www.example.com\n";
        let details = parse_openssl_output(text).unwrap();
        assert_eq!(details.subject.as_deref(), Some("CN = example.com"));
        assert_eq!(details.sans, vec!["example.com", "www.example.com"]);
        assert!(details.not_after.is_some());
    }

    #[test]
    fn generates_self_signed_certificate() {
        if find_openssl().is_none() {
            return;
        }
        let tmp = tempfile::tempdir().unwrap();
        let (cert, key) = generate_self_signed("demo.test", tmp.path(), 7).unwrap();
        assert!(cert.is_file());
        assert!(key.is_file());
        let text = std::fs::read_to_string(&cert).unwrap();
        assert!(text.contains("BEGIN CERTIFICATE"));
    }

    #[test]
    fn missing_certificate_is_a_row_not_a_crash() {
        let mut config = NginxConfig::default();
        config.servers.push(crate::config::ServerInfo {
            cert_path: Some(PathBuf::from("/definitely/missing.pem")),
            names: vec!["x.test".into()],
            ..Default::default()
        });
        let certs = discover(&config);
        assert_eq!(certs.len(), 1);
        assert!(certs[0].error.is_some());
        assert_eq!(certs[0].primary_domain(), "x.test");
    }
}
